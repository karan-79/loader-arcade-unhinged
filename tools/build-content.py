"""Turns content/default.json into hooks/default-content.ts, the built-in
content the plugin starts from (a hooks module cannot import JSON).

    python3 tools/build-content.py
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

content = json.load(open(f'{ROOT}/content/default.json'))
body = json.dumps(content, indent=2, ensure_ascii=False)

with open(f'{ROOT}/hooks/default-content.ts', 'w') as f:
    f.write('// Generated by tools/build-content.py from content/default.json. Do not edit by hand.\n\n')
    f.write("import type { Content } from './content'\n\n")
    f.write(f'export const DEFAULT_CONTENT: Content = {body}\n')

print(f"{len(content['rivals'])} rivals written to hooks/default-content.ts")
